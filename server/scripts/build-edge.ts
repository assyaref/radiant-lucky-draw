/**
 * Bundles the Express backend into a single Supabase Edge Function.
 *
 *   bun scripts/build-edge.ts
 *
 * Output: ../supabase/functions/api/app.bundle.js (+ index.ts entry, deno.json)
 * npm dependencies stay external and are rewritten to `npm:` specifiers
 * using the versions in package.json, so Supabase resolves them at deploy.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join } from 'path';

const root = join(import.meta.dir, '..');
const outDir = join(root, '../supabase/functions/api');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const deps: Record<string, string> = pkg.dependencies;

// 1. regenerate model metadata from schema.prisma
await import('./gen-db-meta.ts');

// 2. bundle
const externals = Object.keys(deps);
const result = await Bun.build({
  entrypoints: [join(root, 'src/edge.ts')],
  target: 'node',
  format: 'esm',
  minify: { whitespace: false, syntax: true, identifiers: true },
  external: [...externals, 'crypto', 'path', 'fs', 'http', 'node:*'],
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
// keep line breaks (readable stack traces) but drop indentation to stay small
let code = (await result.outputs[0].text()).replace(/^[ \t]+/gm, '');

// 3. bare specifiers → npm:/node: specifiers
const used = new Set<string>();
code = code.replace(/(from\s*|import\s*\(\s*|import\s*)(["'])([^"'./][^"']*)\2/g, (m, pre, quote, spec) => {
  if (spec.startsWith('npm:') || spec.startsWith('node:') || spec.startsWith('jsr:')) return m;
  if (['crypto', 'path', 'fs', 'http'].includes(spec)) return `${pre}${quote}node:${spec}${quote}`;
  const name = spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0];
  const version = deps[name];
  if (!version) throw new Error(`Unlisted dependency in bundle: ${spec}`);
  used.add(name);
  return `${pre}${quote}npm:${name}@${version}${spec.slice(name.length)}${quote}`;
});

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'app.bundle.js'),
  `// AUTO-GENERATED by server/scripts/build-edge.ts — do not edit. Source: server/src\n${code}`,
);
writeFileSync(
  join(outDir, 'index.ts'),
  `// Supabase Edge Function \`api\` — the Express backend (server/src), bundled by server/scripts/build-edge.ts\nimport './app.bundle.js';\n`,
);
writeFileSync(join(outDir, 'deno.json'), JSON.stringify({ compilerOptions: { lib: ['deno.ns', 'dom'] } }, null, 2) + '\n');
console.log(`edge bundle: ${(code.length / 1024).toFixed(1)} KB, npm deps: ${[...used].sort().join(', ')}`);
