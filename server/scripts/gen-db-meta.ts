/**
 * Generates src/lib/db-meta.ts from prisma/schema.prisma.
 *
 * schema.prisma stays the single description of the data model; this script
 * extracts what the lightweight Prisma-compatible client (src/lib/prisma.ts)
 * needs at runtime: table names, field → column mapping, defaults and
 * relations. Run with:  bun scripts/gen-db-meta.ts
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const root = join(import.meta.dir, '..');
const schema = readFileSync(join(root, 'prisma/schema.prisma'), 'utf8');

const SCALARS = new Set(['String', 'Int', 'Float', 'Boolean', 'DateTime', 'Json', 'BigInt', 'Decimal']);

interface FieldMeta {
  column: string;
  type: string;
  optional: boolean;
  defaultUuid?: boolean;
  defaultNow?: boolean;
  updatedAt?: boolean;
}
interface RelationMeta {
  model: string;
  list: boolean;
  /** local FK fields (this model holds the FK) */
  fields?: string[];
  references?: string[];
  name?: string;
}
interface ModelMeta {
  table: string;
  fields: Record<string, FieldMeta>;
  relations: Record<string, RelationMeta>;
}

const models: Record<string, ModelMeta> = {};
const modelRe = /model\s+(\w+)\s*\{([\s\S]*?)\n\}/g;
let m: RegExpExecArray | null;
while ((m = modelRe.exec(schema))) {
  const [, name, body] = m;
  const meta: ModelMeta = { table: name, fields: {}, relations: {} };
  for (const raw of body.split('\n')) {
    const line = raw.replace(/\/\/.*$/, '').trim();
    if (!line) continue;
    const mapM = line.match(/^@@map\("([^"]+)"\)/);
    if (mapM) {
      meta.table = mapM[1];
      continue;
    }
    if (line.startsWith('@@')) continue;
    const fm = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
    if (!fm) continue;
    const [, fname, ftype, list, opt, attrs] = fm;
    if (SCALARS.has(ftype)) {
      const col = attrs.match(/@map\("([^"]+)"\)/);
      meta.fields[fname] = {
        column: col ? col[1] : fname,
        type: ftype,
        optional: !!opt,
        ...(attrs.includes('@default(uuid())') ? { defaultUuid: true } : {}),
        ...(attrs.includes('@default(now())') ? { defaultNow: true } : {}),
        ...(attrs.includes('@updatedAt') ? { updatedAt: true } : {}),
      };
    } else {
      const rel: RelationMeta = { model: ftype, list: !!list };
      const rf = attrs.match(/fields:\s*\[([^\]]+)\]/);
      const rr = attrs.match(/references:\s*\[([^\]]+)\]/);
      const rn = attrs.match(/@relation\("([^"]+)"/);
      if (rf && rr) {
        rel.fields = rf[1].split(',').map((s) => s.trim());
        rel.references = rr[1].split(',').map((s) => s.trim());
      }
      if (rn) rel.name = rn[1];
      meta.relations[fname] = rel;
    }
  }
  models[name] = meta;
}

// Resolve back-relations (the side without `fields`) to the FK on the other model.
for (const [name, meta] of Object.entries(models)) {
  for (const [rname, rel] of Object.entries(meta.relations)) {
    if (rel.fields) continue;
    const other = models[rel.model];
    const back = Object.values(other.relations).find(
      (r) => r.model === name && r.fields && (rel.name ? r.name === rel.name : !r.name),
    );
    if (!back) throw new Error(`Cannot resolve relation ${name}.${rname}`);
    (rel as any).foreignFields = back.fields;
    (rel as any).foreignReferences = back.references;
  }
}

const out = `/* AUTO-GENERATED by scripts/gen-db-meta.ts from prisma/schema.prisma — do not edit */
export const DB_META: Record<string, any> = JSON.parse(${JSON.stringify(JSON.stringify(models))});
`;
writeFileSync(join(root, 'src/lib/db-meta.ts'), out);
console.log(`db-meta: ${Object.keys(models).length} models`);
